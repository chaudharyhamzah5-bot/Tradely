/* Welcome screen, sign up / login, log out, delete account, profile delete confirmation. Runs against the fake Supabase in harness.js. */
const fs = require('fs'), path = require('path');
const { makeServer, makeDevice, sleep, ok, summary } = require('./harness');
const until = async (fn, ms = 6000) => { const end = Date.now() + ms; while (Date.now() < end) { try { if (await fn()) return true; } catch (e) {} await sleep(50); } return false; };
const type = (w, el, v) => { el.value = v; el.dispatchEvent(new w.Event('input', { bubbles: true })); };
const CFG = 'tradely_sync_cfg_v1', WIPE = 'tradely_sync_wipe_v1';
const URL_OK = 'https://abc.supabase.co', KEY_OK = 'test-anon-key-0123456789abcdef';

(async () => {
    console.log('1. First start: Fresh start / Login, the app is locked until you are in');
    const S = makeServer(); S.sqlRan = false;
    let D = makeDevice(S, null, { noCfg: true }); await sleep(100);
    let w = D.w, d = w.document;
    ok(d.querySelector('#tg-fresh') && d.querySelector('#tg-login'), 'welcome shows two choices: Fresh start and Login');
    ok(w.TradelySync.status().k === 'login' && !w.TradelySync.account(), 'not signed in, app gated');
    ok(/app_data/.test(w.TRADELY_SQL) && /delete_my_account/.test(w.TRADELY_SQL) && /tradely_auto_confirm/.test(w.TRADELY_SQL), 'Copy SQL text has the table, auto-confirm and delete-account function');
    ok(w.TRADELY_SQL === fs.readFileSync(path.join(__dirname, '..', 'supabase', 'setup.sql'), 'utf8'), 'cloud-sql.js is in sync with supabase/setup.sql (run npm run sql if this fails)');

    console.log('2. Fresh start: URL + key, Copy SQL, green light, then sign up');
    d.querySelector('#tg-fresh').click();
    ok(d.querySelector('#tg-url') && d.querySelector('#tg-key') && d.querySelector('#tg-copy'), 'two fields and the Copy SQL button are there');
    ok(d.querySelector('#tg-next').disabled, 'Continue is locked until the light is green');
    type(w, d.querySelector('#tg-url'), URL_OK); type(w, d.querySelector('#tg-key'), 'x'.repeat(30));
    ok(await until(() => /not accepted/.test(d.querySelector('#tg-lt').textContent)), 'wrong key: red light and a clear message');
    type(w, d.querySelector('#tg-key'), KEY_OK);
    ok(await until(() => /Copy SQL/.test(d.querySelector('#tg-lt').textContent)), 'SQL not run yet: tells you to run it');
    ok(d.querySelector('#tg-next').disabled, 'still locked');
    S.sqlRan = true;
    ok(await until(() => !d.querySelector('#tg-next').disabled, 7000), 'after the SQL is run the light turns green by itself');
    ok(/live/i.test(d.querySelector('#tg-lt').textContent), 'message says the project is live');
    d.querySelector('#tg-next').click();
    d.querySelector('#tg-name').value = 'Ali Khan'; d.querySelector('#tg-email').value = 'ali@x.com'; d.querySelector('#tg-pass').value = '123';
    d.querySelector('#tg-go').click(); await sleep(50);
    ok(/at least 6/.test(d.querySelector('#tg-err').textContent) && !S.users['ali@x.com'], 'short password is refused');
    d.querySelector('#tg-pass').value = 'secret1'; d.querySelector('#tg-go').click();
    ok(await until(() => !d.getElementById('ts-overlay') || !d.querySelector('#tg-go')), 'sign up works, no verification step');
    await D.idle();
    const acc = w.TradelySync.account();
    ok(acc && acc.email === 'ali@x.com' && acc.name === 'Ali Khan', 'account shows email + name (Settings > Account reads this)');
    ok(S.users['ali@x.com'].name === 'Ali Khan', 'name is stored in the Supabase user');
    ok(JSON.parse(D.dump()[CFG]).url === URL_OK && JSON.parse(D.dump()[CFG]).anonKey === KEY_OK, 'URL + key remembered on this device');

    console.log('3. Sign up when the project returns no session / still wants confirmation');
    S.noToken = true; let N = makeDevice(S, null, { noCfg: true }); await sleep(50);
    N.w.document.querySelector('#tg-fresh').click(); type(N.w, N.w.document.querySelector('#tg-url'), URL_OK); type(N.w, N.w.document.querySelector('#tg-key'), KEY_OK);
    await until(() => !N.w.document.querySelector('#tg-next').disabled); N.w.document.querySelector('#tg-next').click();
    N.w.document.querySelector('#tg-name').value = 'Nora'; N.w.document.querySelector('#tg-email').value = 'nora@x.com'; N.w.document.querySelector('#tg-pass').value = 'secret1'; N.w.document.querySelector('#tg-go').click();
    await until(() => N.w.TradelySync.account()); ok(N.w.TradelySync.account() && N.w.TradelySync.account().name === 'Nora', 'no session in the answer: app signs in by itself');
    S.noToken = false; S.requireConfirm = true; let M = makeDevice(S, null, { noCfg: true }); await sleep(50);
    M.w.document.querySelector('#tg-fresh').click(); type(M.w, M.w.document.querySelector('#tg-url'), URL_OK); type(M.w, M.w.document.querySelector('#tg-key'), KEY_OK);
    await until(() => !M.w.document.querySelector('#tg-next').disabled); M.w.document.querySelector('#tg-next').click();
    M.w.document.querySelector('#tg-name').value = 'Mo'; M.w.document.querySelector('#tg-email').value = 'mo@x.com'; M.w.document.querySelector('#tg-pass').value = 'secret1'; M.w.document.querySelector('#tg-go').click();
    ok(await until(() => /Copy SQL/.test((M.w.document.querySelector('#tg-err') || {}).textContent || '')) && !M.w.TradelySync.account(), 'confirmation still ON: clear message, points to the SQL');
    S.requireConfirm = false;

    console.log('4. Login on another device');
    let L = makeDevice(S, null, { noCfg: true }); await sleep(50); const ld = L.w.document;
    ld.querySelector('#tg-login').click();
    type(L.w, ld.querySelector('#tg-url'), 'abc.supabase.co/'); type(L.w, ld.querySelector('#tg-key'), KEY_OK);
    ld.querySelector('#tg-email').value = 'ali@x.com'; ld.querySelector('#tg-pass').value = 'wrong-pass'; ld.querySelector('#tg-go').click();
    ok(await until(() => /Wrong email or password/.test(ld.querySelector('#tg-err').textContent)), 'wrong password is refused');
    ld.querySelector('#tg-pass').value = 'secret1'; ld.querySelector('#tg-go').click();
    await until(() => L.w.TradelySync.account()); await L.idle();
    ok(L.w.TradelySync.account().name === 'Ali Khan', 'login brings the name back (URL typed without https:// also works)');

    console.log('5. Data syncs between the two devices with the same login');
    D.w.TradelyProfiles.create('Ali', 'ali', ''); D = D.reload(); await D.idle(); const ali = D.profile().id;
    D.w.localStorage.setItem('tradely_notes', JSON.stringify([{ id: 'n1', text: 'hello from D' }]));
    await D.idbPut('tradely_certificates', [{ id: 'c1', img: 'data:x' }]); await D.sync();
    await L.sync(); L = L.reload(); await L.idle();
    ok(L.ids().includes(ali) && L.rawKeys().some(k => k === 'tp:' + ali + ':tradely_notes'), 'second device receives the profile and its data');

    console.log('6. Log out: confirmation, upload first, this device is wiped, cloud keeps everything');
    S.offline = true; D.w.localStorage.setItem('tradely_notes', JSON.stringify([{ id: 'n1', text: 'offline edit' }])); await sleep(100);
    D.w.TradelySync.signOut(); const dd = D.w.document;
    ok(!!dd.querySelector('#pp-yes') && /Log out/.test(dd.getElementById('ts-popup').textContent), 'asks for confirmation first');
    dd.querySelector('#pp-yes').click();
    ok(await until(() => /not uploaded|lost/i.test(dd.querySelector('#pp-msg').textContent)), 'unsent changes: warns before logging out');
    ok(!D.dump()[WIPE], 'nothing wiped yet'); dd.querySelector('#pp-no').click();
    S.offline = false; await D.sync(); const rowsBefore = S.rows.size;
    D.w.TradelySync.signOut(); dd.querySelector('#pp-yes').click();
    ok(await until(() => D.dump()[WIPE]), 'online + everything uploaded: logout goes through');
    ok(D.reloads > 0, 'app restarts');
    let D2 = D.reload(); ok(await until(() => !D2.dump()[WIPE] && !D2.rawKeys().some(k => k.startsWith('tp:') || k.startsWith('tradely_profiles') || k === 'tradely_sync_meta_v1')), 'on restart this device\'s data is wiped');
    ok(D2.rawKeys().includes(CFG), 'URL + key stay, so Login is one step');
    ok((await D2.idbAll()).length === 0, 'IndexedDB (certificates) wiped too');
    ok(S.rows.size >= rowsBefore && JSON.stringify(S.list('ls:' + ali)).includes('offline edit'), 'cloud still has all data (incl. the last edit)');
    D2 = D2.reload(); await sleep(100);
    ok(D2.w.document.querySelector('#tg-go') && D2.w.document.querySelector('#tg-url').value === URL_OK, 'next start shows Login with the project already filled in');
    ok(D2.w.document.querySelector('#tg-proj').classList.contains('hidden') && !!D2.w.document.querySelector('#tg-email') && !!D2.w.document.querySelector('#tg-pass'), 'Login on a known device asks only for email + password');

    console.log('7. A different account logs in on a device that still holds old data: old data is wiped, never uploaded');
    L.w.TradelySync._meta.session = null; L = L.reload(); await sleep(100);   // session lost (e.g. refresh token revoked), data still on the device
    ok(!!L.w.document.querySelector('#tg-go'), 'login screen appears by itself');
    await L.signIn('bob@x.com', 'bobpass1', 'up', 'Bob');
    ok(await until(() => L.dump()[WIPE] || L.reloads > 0), 'other account detected: wipe requested');
    L = L.reload(); await sleep(400); L = L.reload(); await L.idle(); await L.sync();    // 1st load wipes, 2nd load is the clean start
    ok(L.w.TradelySync.account() && L.w.TradelySync.account().email === 'bob@x.com', 'Bob is signed in after the wipe');
    ok(!L.rawKeys().some(k => k === 'tp:' + ali + ':tradely_notes'), 'Ali\'s data is gone from this device');
    const bobId = S.users['bob@x.com'].id;
    ok(![...S.rows.values()].some(r => r.user_id === bobId && /hello from D|offline edit/.test(r.value || '')), 'Ali\'s data was NOT uploaded into Bob\'s account');

    console.log('8. Delete account: confirmations, wrong password, A to Z');
    S.noDeleteFn = true;
    L.w.TradelyProfiles.create('Bob', 'bob', ''); L = L.reload(); await L.idle(); L.w.localStorage.setItem('tradely_notes', '[{"id":"b1","text":"bob note"}]'); await L.sync();
    ok([...S.rows.values()].some(r => r.user_id === bobId), 'Bob has data in the cloud');
    const ld2 = L.w.document; L.w.TradelySync.deleteAccount();
    const yes = () => ld2.querySelector('#pp-yes');
    ok(yes().disabled, 'delete button is locked at first');
    ld2.querySelector('#da-ack').checked = true; type(L.w, ld2.querySelector('#da-pass'), 'bobpass1'); type(L.w, ld2.querySelector('#da-type'), 'delete');
    ld2.querySelector('#da-ack').dispatchEvent(new L.w.Event('change'));
    ok(yes().disabled, 'lowercase "delete" is not enough');
    type(L.w, ld2.querySelector('#da-type'), 'DELETE'); ok(!yes().disabled, 'checkbox + password + DELETE unlock it');
    type(L.w, ld2.querySelector('#da-pass'), 'nope'); yes().click();
    ok(await until(() => /Wrong password/.test(ld2.querySelector('#pp-msg').textContent)) && S.users['bob@x.com'], 'wrong password: nothing deleted');
    type(L.w, ld2.querySelector('#da-pass'), 'bobpass1'); yes().click();
    ok(await until(() => /delete function/.test(ld2.querySelector('#pp-msg').textContent)) && S.users['bob@x.com'], 'old SQL (no delete function): clear message, nothing deleted');
    ok(/Copy SQL/.test(ld2.getElementById('ts-popup').textContent), 'Copy SQL button offered');
    S.noDeleteFn = false; yes().click();
    ok(await until(() => L.dump()[WIPE]), 'delete goes through');
    ok(!S.users['bob@x.com'] && ![...S.rows.values()].some(r => r.user_id === bobId), 'login and every row are gone from Supabase');
    let L2 = L.reload(); ok(await until(() => !L2.dump()[WIPE] && !L2.rawKeys().some(k => k.startsWith('tp:'))), 'this device is wiped too');
    L2 = L2.reload(); await sleep(100); ok(!!L2.w.document.querySelector('#tg-go') && !L2.w.TradelySync.account(), 'back at the login screen');
    await L2.signIn('bob@x.com', 'bobpass1', 'in'); ok(/Wrong email or password/.test(L2.w.document.querySelector('#tg-err').textContent), 'the deleted account cannot log in any more');

    console.log('9. Profile delete: confirmations, cloud checked first, offline stays safe');
    let P = makeDevice(S, null, { noCfg: true }); await sleep(50);
    P.w.document.querySelector('#tg-login').click(); type(P.w, P.w.document.querySelector('#tg-url'), URL_OK); type(P.w, P.w.document.querySelector('#tg-key'), KEY_OK);
    await P.signIn('ali@x.com', 'secret1', 'in'); await P.idle();
    P.w.TradelyProfiles.create('Temp', 'temp', ''); P = P.reload(); await P.idle(); const tmp = P.profile().id;
    P.w.localStorage.setItem('tradely_notes', '[{"id":"t1","text":"temp note"}]'); await P.sync();
    ok(S.list('ls:' + tmp).length > 0, 'temp profile data is in the cloud');
    P.w.document.body.insertAdjacentHTML('beforeend', '<aside><div class="p-3 border-t"></div></aside>');
    P.w.eval(fs.readFileSync(path.join(__dirname, '..', 'app', 'js', 'profiles-ui.js'), 'utf8')); await sleep(50);
    const pd = P.w.document; ok(await until(() => pd.querySelector('#profile-btn')), 'profile button is mounted');
    pd.querySelector('#profile-btn').click(); pd.querySelector('#tp-edit').click(); pd.querySelector('#tp-del').click();
    const pok = () => pd.querySelector('#tp-ok');
    ok(pok().disabled, 'Delete forever is locked at first');
    pd.querySelector('#tp-ack').checked = true; type(P.w, pd.querySelector('#tp-confirm'), 'DELETE'); pd.querySelector('#tp-ack').dispatchEvent(new P.w.Event('change'));
    ok(!pok().disabled, 'checkbox + DELETE unlock it');
    S.offline = true; pok().click();
    ok(await until(() => /offline/i.test(pd.querySelector('#tp-err').textContent)) && !pd.querySelector('#tp-force').classList.contains('hidden'), 'offline: tells you, offers "Delete here anyway"');
    ok(P.ids().includes(tmp) && S.list('ls:' + tmp).length > 0, 'nothing was deleted yet (local or cloud)');
    S.offline = false; pok().click();
    ok(await until(() => !P.ids().includes(tmp)), 'online: profile removed locally');
    ok(S.list('ls:' + tmp).length === 0 && S.list('idb:' + tmp).length === 0, 'and every cloud row of it is gone');
    await P.sync(); await P.sync();
    const tomb = JSON.parse(S.list('meta').filter(r => !r.deleted)[0].value).find(x => x.id === tmp);
    ok(tomb && tomb.deleted === true && !('name' in tomb) && !('username' in tomb) && !('pin' in tomb), 'profile list keeps only an id tombstone for it (no name, username or PIN)');
    ok(await P.w.TradelySync.purgeProfile('doesnotexist') === true, 'purging an empty profile is fine');
    summary();
})().catch(e => { console.error('CRASH', e); process.exit(2); });
