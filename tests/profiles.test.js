const { makeServer, makeDevice, sleep, ok, summary } = require('./harness');
(async () => {
    const S = makeServer();
    console.log('1. Device A: first profile "Ali", sign up, data goes to Ali only');
    let A = makeDevice(S);
    ok(A.w.TradelyProfiles.create('Ali', 'ali', '') === '', 'create Ali');
    A = A.reload(); const ali = A.profile().id;
    ok(ali && A.w.TradelySync.configured, 'Ali active, sync configured');
    A.w.localStorage.setItem('tradely_notes', JSON.stringify([{ id: 'n1', text: 'ali note' }]));
    A.w.localStorage.setItem('tradely_ai_config_v1', JSON.stringify({ providers: { x: { apiKey: 'SECRET-KEY-123' } } }));
    A.w.localStorage.setItem('tradely_calc_prefs', '{"lot":1}');
    await A.signIn('me@x.com', 'secret1', 'up');
    await A.sync();
    ok(S.rows.size > 0, 'rows reached the fake server');
    ok(S.list('ls:' + ali).some(r => r.key.startsWith('tradely_notes')), 'Ali notes stored under ns ls:' + ali);
    ok(JSON.stringify(S.list('ls:' + ali)).includes('SECRET-KEY-123'), 'AI API key is saved in the cloud under Ali');

    console.log('2. Device A: second profile "Sara" with different data');
    A.w.TradelyProfiles.create('Sara', 'sara', '1234'); A = A.reload(); const sara = A.profile().id;
    ok(sara && sara !== ali, 'Sara is active (id differs)');
    ok(A.w.localStorage.getItem('tradely_notes') === null, 'Sara starts empty (Ali notes not visible)');
    A.w.localStorage.setItem('tradely_notes', JSON.stringify([{ id: 's1', text: 'sara note' }]));
    await A.sync();
    const aliRows = JSON.stringify(S.list('ls:' + ali)), saraRows = JSON.stringify(S.list('ls:' + sara));
    ok(aliRows.includes('ali note') && !aliRows.includes('sara note'), 'cloud: Ali namespace has only Ali data');
    ok(saraRows.includes('sara note') && !saraRows.includes('ali note'), 'cloud: Sara namespace has only Sara data');
    ok(S.list('meta').length === 1, 'cloud: profile list stored once');

    console.log('3. Device B (fresh): sign in, gets both profiles, data isolated');
    let B = makeDevice(S); await B.signIn('me@x.com', 'secret1', 'in'); B = B.reload();
    ok(B.ids().length === 2 && B.ids().includes(ali) && B.ids().includes(sara), 'B sees both profiles');
    ok(B.w.TradelyProfiles.list().find(p => p.id === sara).hasPin, 'Sara PIN lock came along');
    ok(B.rawKeys().some(k => k === 'tp:' + ali + ':tradely_notes') && B.rawKeys().some(k => k === 'tp:' + sara + ':tradely_notes'), 'B has notes for both profiles in separate slots');
    ok(B.w.TradelyProfiles.switchTo(ali, '') === '', 'switch to Ali (no PIN)'); B = B.reload();
    ok(B.profile().id === ali && JSON.parse(B.w.localStorage.getItem('tradely_notes'))[0].text === 'ali note', 'as Ali on B: only Ali note');
    ok(B.w.TradelyProfiles.switchTo(sara, '0000') === 'Wrong PIN.', 'Sara wrong PIN rejected on B');
    B.w.TradelyProfiles.switchTo(sara, '1234'); B = B.reload();
    ok(B.profile() && B.profile().id === sara && JSON.parse(B.w.localStorage.getItem('tradely_notes'))[0].text === 'sara note', 'as Sara on B (PIN ok): only Sara note');

    console.log('4. Both devices create a profile at the same time (same username "zed")');
    B.w.TradelyProfiles.create('Zed B', 'zed', ''); B = B.reload(); const zb = B.profile().id;
    A.w.TradelyProfiles.create('Zed A', 'zed', ''); A = A.reload(); const za = A.profile().id;
    A.w.localStorage.setItem('tradely_notes', '[{"id":"za","text":"from A"}]');
    B.w.localStorage.setItem('tradely_notes', '[{"id":"zb","text":"from B"}]');
    await A.sync(); await B.sync(); await A.sync(); await B.sync();
    const la = A.w.TradelyProfiles.list(), lb = B.w.TradelyProfiles.list();
    ok(la.length === 4 && lb.length === 4, 'both devices have all 4 profiles (no profile lost)');
    ok(new Set(la.map(p => p.username)).size === 4 && new Set(lb.map(p => p.username)).size === 4, 'usernames are unique after merge');
    ok(JSON.stringify(la.map(p => [p.id, p.username])) === JSON.stringify(lb.map(p => [p.id, p.username])), 'both devices agree on the list');
    ok(JSON.stringify(S.list('ls:' + za)).includes('from A') && JSON.stringify(S.list('ls:' + zb)).includes('from B'), 'each new profile kept its own data in the cloud');
    const before = S.log.length; await A.sync(); await B.sync();
    ok(S.log.slice(before).filter(l => l.startsWith('POST')).length === 0, 'no sync ping-pong (nothing re-uploaded when idle)');

    console.log('5. Delete a profile on B: gone in cloud and on A, nothing comes back');
    B.w.TradelyProfiles.remove(sara); B = B.reload(); await sleep(300); await B.sync();
    ok(S.list('ls:' + sara).length === 0, 'cloud rows of the deleted profile are removed');
    ok(!B.ids().includes(sara) && !B.rawKeys().some(k => k.startsWith('tp:' + sara + ':')), 'B: profile and its data gone');
    await A.sync();
    ok(!A.ids().includes(sara), 'A: profile removed after sync');
    ok(!A.rawKeys().some(k => k.startsWith('tp:' + sara + ':')), 'A: leftover data of that profile purged');
    ok(A.ids().length === 3 && B.ids().length === 3, 'other 3 profiles untouched on both');
    ok(JSON.stringify(S.list('ls:' + ali)).includes('ali note'), 'Ali data untouched in cloud');
    await A.sync(); await B.sync();
    ok(S.list('ls:' + sara).length === 0 && !A.ids().includes(sara) && !B.ids().includes(sara), 'deleted profile does not resurrect');

    console.log('6. Certificates (IndexedDB): upload, then erase via store.clear() reaches cloud');
    A.w.TradelyProfiles.switchTo(ali, ''); A = A.reload();
    await A.idbPut('tradely_certificates', [{ id: 'c1', img: 'data:x' }]); await A.sync();
    ok(S.list('idb:' + ali).some(r => r.key.startsWith('tradely_certificates') && !r.deleted), 'certificate uploaded under idb:' + ali);
    await A.idbClear(); await sleep(50); await A.sync();
    ok(!S.list('idb:' + ali).some(r => !r.deleted && r.key.startsWith('tradely_certificates::')), 'after clear(): certificate removed from cloud');
    let B2 = makeDevice(S); await B2.signIn('me@x.com', 'secret1', 'in'); B2 = B2.reload();
    B2.w.TradelyProfiles.switchTo(ali, ''); B2 = B2.reload();
    ok((await B2.idbAll()).length === 0 || !JSON.stringify(await B2.idbAll()).includes('c1'), 'fresh device does not get the erased certificate back');

    console.log('7. Offline create, then reconnect');
    S.offline = true; A.w.TradelyProfiles.create('Off', 'off', ''); A = A.reload();
    A.w.localStorage.setItem('tradely_notes', '[{"id":"o1","text":"offline note"}]');
    await sleep(200); S.offline = false; await A.sync(); await A.sync();
    const offId = A.profile().id;
    ok(JSON.stringify(S.list('meta')).includes(offId) && JSON.stringify(S.list('ls:' + offId)).includes('offline note'), 'offline profile + data uploaded after reconnect');
    await B.sync(); ok(B.ids().includes(offId), 'other device receives it');

    console.log('8. API keys: per profile, travel to other devices, removal propagates');
    const ALI_KEY = 'SECRET-KEY-123', ZA_KEY = 'ZA-GROQ-999';
    A.w.TradelyProfiles.switchTo(za, ''); A = A.reload();
    A.w.localStorage.setItem('tradely_groq_api_key', ZA_KEY); A.w.localStorage.setItem('tw_twelvedata_api_key', 'ZA-TW-1');
    await A.sync();
    ok(JSON.stringify(S.list('ls:' + za)).includes(ZA_KEY) && JSON.stringify(S.list('ls:' + za)).includes('ZA-TW-1'), 'Zed A keys stored under Zed A');
    ok(!JSON.stringify(S.list('ls:' + ali)).includes(ZA_KEY) && !JSON.stringify(S.list('ls:' + ali)).includes('ZA-TW-1'), 'Zed A keys are NOT in Ali namespace');
    ok(!JSON.stringify(S.list('ls:' + za)).includes(ALI_KEY), 'Ali key is NOT in Zed A namespace');
    let C = makeDevice(S); await C.signIn('me@x.com', 'secret1', 'in'); C = C.reload();
    C.w.TradelyProfiles.switchTo(ali, ''); C = C.reload();
    ok(JSON.parse(C.w.localStorage.getItem('tradely_ai_config_v1')).providers.x.apiKey === ALI_KEY && C.w.localStorage.getItem('tradely_groq_api_key') === null, 'new device, Ali: gets Ali AI key, no Zed A key');
    C.w.TradelyProfiles.switchTo(za, ''); C = C.reload();
    ok(C.w.localStorage.getItem('tradely_groq_api_key') === ZA_KEY && C.w.localStorage.getItem('tw_twelvedata_api_key') === 'ZA-TW-1' && C.w.localStorage.getItem('tradely_ai_config_v1') === null, 'new device, Zed A: gets Zed A keys only');
    C.w.localStorage.removeItem('tradely_groq_api_key'); await C.sync(); await A.sync();
    ok(A.w.localStorage.getItem('tradely_groq_api_key') === null, 'key removed on one device is removed on the other');

    console.log('9. Psychology feed snapshot');
    const feed = g => JSON.stringify({ generatedAt: g, summary: { daysChecked: 3 }, days: [{ date: '2026-11-01', passed: true }] });
    A.w.localStorage.setItem('tradely_psychology_feed', feed(1000)); await A.sync();
    ok(JSON.stringify(S.list('ls:' + za)).includes('daysChecked'), 'feed snapshot uploaded under Zed A');
    const n0 = S.log.length; A.w.localStorage.setItem('tradely_psychology_feed', feed(2000)); await A.sync();
    ok(S.log.slice(n0).filter(l => l.startsWith('POST')).length === 0, 're-render with a new timestamp only: nothing uploaded');
    A.w.localStorage.setItem('tradely_psychology_feed', JSON.stringify({ generatedAt: 3000, summary: { daysChecked: 9 }, days: [] })); await A.sync();
    ok(JSON.stringify(S.list('ls:' + za)).includes('"daysChecked\\":9') || JSON.stringify(S.list('ls:' + za)).includes('daysChecked\\":9'), 'real content change is uploaded');
    await C.sync(); ok((C.w.localStorage.getItem('tradely_psychology_feed') || '').includes('"daysChecked":9'), 'other device receives the feed');
    ok(!JSON.stringify(S.list('ls:' + ali)).includes('daysChecked'), 'feed of Zed A is not in Ali namespace');
    summary();
})().catch(e => { console.error('CRASH', e); process.exit(2); });
